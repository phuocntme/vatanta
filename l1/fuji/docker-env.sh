#!/usr/bin/env bash
# Fuji chain + Docker services on THIS machine ("VPS on localhost").
# Writes .run/fuji-local.env for:  docker compose --env-file .run/fuji-local.env --profile icm up -d
# (scripts/fuji-local.sh runs this for you.)
#
# Reads .env (see .env.example) and contracts/deployments/fuji.json.
# Containers reach the Fuji node on this machine by IP, because avalanchego rejects unknown Host
# names such as host.docker.internal. The browser keeps using 127.0.0.1.
#   HOST_IP   override the address containers use for this machine
#             (default: Docker Desktop host gateway 192.168.65.254 on macOS, docker0 IP on Linux)
set -euo pipefail
cd "$(dirname "$0")/../.."
[ -f .env ] || { echo "missing .env — cp .env.example .env and fill it"; exit 1; }
set -a; . ./.env; set +a
: "${RELAYER_PK:?RELAYER_PK is empty in .env}" "${L1_RPC:?L1_RPC is empty in .env}" "${C_RPC:?C_RPC is empty in .env}"
[ -f contracts/deployments/fuji.json ] || { echo "missing contracts/deployments/fuji.json — run: contracts/script/deploy.sh .env"; exit 1; }

if [ -z "${HOST_IP:-}" ]; then
  if [ "$(uname)" = "Darwin" ]; then
    HOST_IP=192.168.65.254
  else
    HOST_IP=$(ip -4 -o addr show docker0 2>/dev/null | awk '{print $4}' | cut -d/ -f1 || true)
    HOST_IP=${HOST_IP:-172.17.0.1}
  fi
fi
# URL as seen from inside a container: loopback names become the host's IP
in_docker() { echo "$1" | sed -E "s#//(127\.0\.0\.1|localhost|0\.0\.0\.0)([:/])#//$HOST_IP\2#"; }

# Postgres keeps the password it was first created with, so generate one once and reuse it.
mkdir -p .run
umask 077
if [ -z "${POSTGRES_PASSWORD:-}" ] || [ "$POSTGRES_PASSWORD" = "change-me" ]; then
  [ -f .run/fuji-pg-password ] || openssl rand -hex 16 > .run/fuji-pg-password
  POSTGRES_PASSWORD=$(cat .run/fuji-pg-password)
fi

RELAYER_PORT=${RELAYER_PORT:-8090}
INDEXER_PORT=${INDEXER_PORT:-8091}
WEB_PORT=${WEB_PORT:-4001}
cat > .run/fuji-local.env <<EOF
# generated by l1/fuji/docker-env.sh — Fuji chain, services on this machine (gitignored, has keys)
NETWORK=fuji
RELAYER_PK=$RELAYER_PK
L1_RPC=$(in_docker "$L1_RPC")
C_RPC=$(in_docker "$C_RPC")
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
BATCH_INTERVAL_SECS=${BATCH_INTERVAL_SECS:-600}
FAUCET=0
BIND_HOST=127.0.0.1
WEB_PORT=$WEB_PORT
RELAYER_PORT=$RELAYER_PORT
INDEXER_PORT=$INDEXER_PORT
PUBLIC_RELAYER_URL=http://127.0.0.1:$RELAYER_PORT
PUBLIC_INDEXER_URL=http://127.0.0.1:$INDEXER_PORT
PUBLIC_L1_RPC=${PUBLIC_L1_RPC:-$L1_RPC}
PUBLIC_C_RPC=${PUBLIC_C_RPC:-$C_RPC}
PRIVY_APP_ID=${PRIVY_APP_ID:-}
ICM_RELAYER_VERSION=${ICM_RELAYER_VERSION:-v1.8.4}
EOF
echo "wrote .run/fuji-local.env (containers reach this machine at $HOST_IP)"
