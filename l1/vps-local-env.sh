#!/usr/bin/env bash
# "VPS on this machine": writes .run/vps-local.env so `docker compose` runs the production stack
# (postgres, relayer, indexer, web) against the local Avalanche network from l1/local-up.sh.
#   l1/vps-local-env.sh && docker compose --env-file .run/vps-local.env up -d --build
# Containers reach the node by IP (avalanchego rejects unknown Host names such as host.docker.internal).
# Web on :4001 (allowed origin in Privy), relayer :8090, indexer :8091. Stop `pnpm demo` first.
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; . l1/.local.env; set +a
HOST_IP=${HOST_IP:-192.168.65.254} # Docker Desktop's host gateway; on Linux use the docker0 IP (172.17.0.1)
mkdir -p .run
umask 077
cat > .run/vps-local.env <<EOF
# generated by l1/vps-local-env.sh — local network only (gitignored)
NETWORK=local
RELAYER_PK=$DEPLOYER_PK
L1_RPC=${L1_RPC/127.0.0.1/$HOST_IP}
C_RPC=${C_RPC/127.0.0.1/$HOST_IP}
POSTGRES_PASSWORD=vatanta-local
BATCH_INTERVAL_SECS=60
FAUCET=1
WEB_PORT=4001
RELAYER_PORT=8090
INDEXER_PORT=8091
PUBLIC_RELAYER_URL=http://127.0.0.1:8090
PUBLIC_INDEXER_URL=http://127.0.0.1:8091
PUBLIC_L1_RPC=$L1_RPC
PUBLIC_C_RPC=$C_RPC
PRIVY_APP_ID=${PRIVY_APP_ID:-$(grep -s '^NEXT_PUBLIC_PRIVY_APP_ID=' apps/web/.env.local | cut -d= -f2)}
CLOUDFLARE_TUNNEL_TOKEN=
EOF
echo "wrote .run/vps-local.env"
