#!/usr/bin/env bash
# Start (or reuse) the local Avalanche network with the Vatanta L1 and write l1/.local.env.
#   E2E_CLEAN=1 l1/local-up.sh   → wipe the network and start from scratch
set -euo pipefail
cd "$(dirname "$0")"
export PATH="$HOME/.local/toolchain/avalanche:$PATH"
AV="avalanche --skip-update-check"
NAME=${L1_NAME:-vatanta}
EWOQ=0x8db97C7cEcE249c2b98bDC0226Cc4C2A57BF52FC # well-known local test key address (not a secret)
mkdir -p ../.run
LOG=../.run/avalanche.log
# avalanche-cli is chatty, so its output goes to .run/avalanche.log; on failure show the end of it
av() {
  echo "--- $(date '+%F %T') avalanche $*" >> "$LOG"
  if ! $AV "$@" >> "$LOG" 2>&1; then
    echo "avalanche $* failed. Last lines of .run/avalanche.log:" >&2
    grep -v posthog "$LOG" | tail -25 >&2
    exit 1
  fi
}

# avalanchego and the Subnet-EVM plugin refuse to start below 32768 open files and only print
# "handshake failed" through avalanche-cli, so check (and try to raise) the limit first.
ulimit -n 32768 2>/dev/null || true
FD=$(ulimit -n)
if [ "$FD" != "unlimited" ] && [ "$FD" -lt 32768 ]; then
  echo "open-file limit is $FD; avalanchego needs 32768. Raise it (e.g. 'ulimit -n 32768', or on Linux"
  echo "LimitNOFILE / /etc/security/limits.conf, in Docker --ulimit nofile=32768:32768) and rerun." >&2
  exit 1
fi

if [ "${E2E_CLEAN:-0}" = "1" ]; then
  $AV network clean --hard >/dev/null 2>&1 || $AV network clean >/dev/null 2>&1 || true
  rm -rf "$HOME/.avalanche-cli/subnets/$NAME"
fi

if [ ! -f "$HOME/.avalanche-cli/subnets/$NAME/genesis.json" ]; then
  echo "creating L1 config '$NAME'"
  av blockchain create "$NAME" --evm --proof-of-authority \
    --validator-manager-owner $EWOQ --proxy-contract-owner $EWOQ \
    --evm-chain-id 777001 --evm-token VNT --test-defaults --icm --latest
  ./patch-genesis.py "$HOME/.avalanche-cli/subnets/$NAME/genesis.json"
fi

# (capture first: `cmd | grep -q` + pipefail misreports when grep exits early)
STATUS=$($AV network status 2>&1 || true)
if ! grep -q "Network is Up" <<< "$STATUS"; then
  DESC0=$($AV blockchain describe "$NAME" 2>&1 || true)
  if grep -q "Local Network" <<< "$DESC0"; then
    echo "starting local network"
    av network start
    STATUS=$($AV network status 2>&1 || true)
  fi
fi

if ! grep -q "$(echo $NAME | tr '[:lower:]' '[:upper:]') RPC URLS" <<< "$STATUS"; then
  echo "deploying L1 '$NAME' to the local network (first run takes a few minutes)"
  av blockchain deploy "$NAME" --local
fi

DESC=$($AV blockchain describe "$NAME" 2>&1)
L1_HEX=$(echo "$DESC" | grep "BlockchainID (HEX)" | head -1 | awk -F'|' '{gsub(/ /,"",$4); print $4}')
L1_CB58=$(echo "$DESC" | grep "BlockchainID (CB58)" | head -1 | awk -F'|' '{gsub(/ /,"",$4); print $4}')
L1_RPC="http://127.0.0.1:9654/ext/bc/$L1_CB58/rpc"
C_RPC="http://127.0.0.1:9650/ext/bc/C/rpc"
RELAYER_CFG=$(ls -t "$HOME"/.avalanche-cli/runs/network_*/icm-relayer-config.json 2>/dev/null | head -1)
read C_REG L1_REG < <(python3 - "$RELAYER_CFG" "$L1_CB58" <<'PY'
import json,sys
c=json.load(open(sys.argv[1])); l1=sys.argv[2]
reg={}
for s in c["source-blockchains"]:
    for k,v in s["message-contracts"].items():
        if v.get("message-format")=="off-chain-registry": reg[s["blockchain-id"]]=v["settings"]["teleporter-registry-address"]
print(reg[[k for k in reg if k!=l1][0]], reg[l1])
PY
)
C_HEX=$(cast call 0x0200000000000000000000000000000000000005 "getBlockchainID()(bytes32)" --rpc-url $C_RPC)
cat > .local.env <<EOT
# generated by l1/local-up.sh — local network only
NETWORK=local
C_RPC=$C_RPC
L1_RPC=$L1_RPC
C_CHAIN_ID=$(cast chain-id --rpc-url $C_RPC)
L1_CHAIN_ID=$(cast chain-id --rpc-url $L1_RPC)
C_BLOCKCHAIN_ID=$C_HEX
L1_BLOCKCHAIN_ID=$L1_HEX
C_ICM_REGISTRY=$C_REG
L1_ICM_REGISTRY=$L1_REG
# avalanche-cli's well-known local "ewoq" key (prefunded on local networks only; never use elsewhere)
DEPLOYER_PK=0x56289e99c94b6912bfc12adc093c9b51124f0dc54ac7a766b2bc5ccf558d8027
EOT
echo "wrote l1/.local.env"
cat .local.env | grep -v PK
